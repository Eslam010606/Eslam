/* ============================================================
   i18n engine
   ============================================================ */
const ED_I18N = {
  lang: DEFAULT_LANG,
  supported: ["en", "ar", "fr", "de", "es", "it", "pt", "ru", "zh", "ja"],
  _dict: LOCALES,
  _merged: {},

  build(lang) {
    this.lang = lang;
    this._merged[lang] = deepMerge(LOCALES.en, LOCALES[lang] || {});
  },

  /* prepare a locale for lookup WITHOUT changing the active site language */
  prepare(code) {
    if (code && !this._merged[code]) {
      this._merged[code] = deepMerge(LOCALES.en, LOCALES[code] || {});
    }
  },

  gt(langKey, path) {
    langKey = langKey || this.lang;
    const seg = path.split(".");
    let node = this._merged[langKey] || LOCALES.en;
    for (const s of seg) {
      if (node && typeof node === "object" && s in node) node = node[s];
      else {
        node = this._resolve(LOCALES.en, seg);
        break;
      }
    }
    if (typeof node === "string") return node;
    if (Array.isArray(node)) return node;
    return path;
  },

  _resolve(obj, seg) {
    let n = obj;
    for (const s of seg) {
      if (n && typeof n === "object" && s in n) n = n[s];
      else return undefined;
    }
    return n;
  },

  /* get an array (deep-merged arrays come from the active locale) */
  gtArr(langKey, path) {
    const v = this.gt(langKey, path);
    return Array.isArray(v) ? v : [];
  },
};

function deepMerge(base, extra) {
  const out = Array.isArray(base) ? base.slice() : Object.assign({}, base);
  if (!extra || typeof extra !== "object") return out;
  for (const k in extra) {
    if (!Object.prototype.hasOwnProperty.call(extra, k)) continue;
    const b = out[k];
    const e = extra[k];
    if (
      b &&
      e &&
      typeof b === "object" &&
      typeof e === "object" &&
      !Array.isArray(b) &&
      !Array.isArray(e)
    ) {
      out[k] = deepMerge(b, e);
    } else {
      out[k] = e;
    }
  }
  return out;
}

ED_I18N.build(DEFAULT_LANG);
window.ED_I18N = ED_I18N;